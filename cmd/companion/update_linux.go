func defaultInstallDir(home string) string {
	return filepath.Join(home, ".local", "bin")
}

func releaseAssetName(ver string) (string, error) {
	switch runtime.GOARCH {
	case "amd64", "arm64":
		return fmt.Sprintf("souls-house-companion-%s-linux-%s.tar.gz", ver, runtime.GOARCH), nil
	default:
		return "", fmt.Errorf("unsupported Linux architecture: %s", runtime.GOARCH)
	}
}

func restartTrayUnit(ctx context.Context) error {
	// Use try-restart --no-block as the final step after the companion is
	// verified: renaming over a running tray binary is safe on Linux (the old
	// process keeps its inode), and never stopping the tray mid-upgrade avoids
	// killing an updater launched from the tray's cgroup.
	_, err := systemctlOutput(ctx, "try-restart", "--no-block", trayUnit)
	return err
}

// installedUnitConfigForHome parses ExecStart= from the installed companion
// systemd user unit if present, returning both the executable path and any
// configured --state-dir argument.
func installedUnitConfigForHome(home string) (installedUnitConfig, bool, error) {
	path := userUnitPath(home)
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return installedUnitConfig{}, false, nil
	}
	if err != nil {
		return installedUnitConfig{}, false, err
	}
	if !info.Mode().IsRegular() {
		return installedUnitConfig{}, false, errors.New("companion unit file is not a regular file")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return installedUnitConfig{}, false, err
	}
	return parseSystemdExecStart(string(data))
}

func parseSystemdExecStart(content string) (installedUnitConfig, bool, error) {
	for _, rawLine := range strings.Split(content, "\n") {
		line := strings.TrimSpace(rawLine)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
			continue
		}
		if !strings.HasPrefix(line, "ExecStart=") {
			continue
		}
		val := strings.TrimSpace(strings.TrimPrefix(line, "ExecStart="))
		if val == "" {
			continue
		}
		// Strip optional systemd ExecStart prefixes (@, -, :, +, !).
		val = strings.TrimLeft(val, "@-:+!")
		if val == "" {
			continue
		}
		tokens, err := splitSystemdArgs(val)
		if err != nil {
			return installedUnitConfig{}, false, err
		}
		if len(tokens) == 0 || !filepath.IsAbs(tokens[0]) {
			return installedUnitConfig{}, false, errors.New("non-absolute ExecStart in unit file")
		}
		cfg := installedUnitConfig{binaryPath: tokens[0]}
		for i := 1; i < len(tokens); i++ {
			arg := tokens[i]
			switch {
			case arg == "--state-dir" || arg == "-state-dir":
				if i+1 >= len(tokens) || !filepath.IsAbs(tokens[i+1]) {
					return installedUnitConfig{}, false, errors.New("invalid --state-dir in unit ExecStart")
				}
				cfg.stateDir = tokens[i+1]
				i++
			case strings.HasPrefix(arg, "--state-dir="):
				v := strings.TrimPrefix(arg, "--state-dir=")
				if !filepath.IsAbs(v) {
					return installedUnitConfig{}, false, errors.New("invalid --state-dir in unit ExecStart")
				}
				cfg.stateDir = v
			case strings.HasPrefix(arg, "-state-dir="):
				v := strings.TrimPrefix(arg, "-state-dir=")
				if !filepath.IsAbs(v) {
					return installedUnitConfig{}, false, errors.New("invalid --state-dir in unit ExecStart")
				}
				cfg.stateDir = v
			}
		}
		return cfg, true, nil
	}
	return installedUnitConfig{}, false, nil
}

// splitSystemdArgs splits a systemd ExecStart value into tokens, supporting
// double-quoted arguments with \" and \\ escapes as generated by installUnit.
func splitSystemdArgs(s string) ([]string, error) {
	var tokens []string
	var cur strings.Builder
	inToken := false
	inQuote := false
	for i := 0; i < len(s); i++ {
		ch := s[i]
		if inQuote {
			if ch == '\\' && i+1 < len(s) {
				i++
				cur.WriteByte(s[i])
				continue
			}
			if ch == '"' {
				inQuote = false
				continue
			}
			cur.WriteByte(ch)
			continue
		}
		switch ch {
		case ' ', '\t':
			if inToken {
				tokens = append(tokens, cur.String())
				cur.Reset()
				inToken = false
			}
		case '"':
			inQuote = true
			inToken = true
		default:
			cur.WriteByte(ch)
			inToken = true
		}
	}
	if inQuote {
		return nil, errors.New("malformed quoted ExecStart in unit file")
	}
	if inToken {
		tokens = append(tokens, cur.String())
	}
	return tokens, nil
}

func queryUnitActiveAndPID(ctx context.Context, unitName string) (string, int, error) {
	output, err := systemctlOutput(ctx, "show", "--property=ActiveState", "--property=MainPID", unitName)
	if err != nil {
		return "", 0, err
	}
	var active string
	var pid int
	sawPID := false
	for _, line := range strings.Split(strings.TrimSuffix(string(output), "\n"), "\n") {
		key, value, ok := strings.Cut(line, "=")
		if !ok || value == "" {
			return "", 0, errors.New("invalid unit runtime properties")
		}
		switch key {
		case "ActiveState":
			active = value
		case "MainPID":
			n, err := strconv.Atoi(value)
			if err != nil || n < 0 {
				return "", 0, errors.New("invalid MainPID")
			}
			pid = n
			sawPID = true
		}
	}
	if active == "" || !sawPID {
		return "", 0, errors.New("missing unit runtime properties")
	}
	return active, pid, nil
}

// verifyRunningBinary confirms that the restarted systemd user service is
// active and its MainPID is executing the newly installed binary on disk (not
// a stale/deleted old process). This checks local systemd + /proc/<pid>/exe
// only; an offline house does not cause a failed start.
func verifyRunningBinary(ctx context.Context, expectedBin string) error {
	return verifyRunningBinaryWithProc(ctx, expectedBin, "/proc", queryUnitActiveAndPID, 5*time.Second)
}

func verifyRunningBinaryWithProc(
	ctx context.Context,
	expectedBin string,
	procRoot string,
	query func(context.Context, string) (string, int, error),
	timeout time.Duration,
) error {
	resolvedExpected, err := filepath.EvalSymlinks(expectedBin)
	if err != nil {
		return err
	}
	expectedInfo, err := os.Stat(resolvedExpected)
	if err != nil {
		return err
	}
	deadline := time.Now().Add(timeout)
	var lastErr error
	for {
		active, pid, err := query(ctx, companionUnit)
		if err != nil {
			lastErr = err
		} else if active == "failed" || active == "inactive" {
			return fmt.Errorf("service is %s after start", active)
		} else if active == "active" && pid > 0 {
			exeLinkPath := filepath.Join(procRoot, strconv.Itoa(pid), "exe")
			linkTarget, linkErr := os.Readlink(exeLinkPath)
			if linkErr != nil {
				lastErr = linkErr
			} else if strings.HasSuffix(linkTarget, " (deleted)") {
				return errors.New("running service is still executing a deleted previous binary")
			} else {
				procInfo, statErr := os.Stat(exeLinkPath)
				if statErr != nil {
					lastErr = statErr
				} else if os.SameFile(expectedInfo, procInfo) {
					return nil
				} else {
					lastErr = errors.New("running service executable does not match upgraded binary")
				}
			}
		} else {
			lastErr = fmt.Errorf("service not active yet (state=%s pid=%d)", active, pid)
		}
		if time.Now().After(deadline) {
			if lastErr != nil {
				return lastErr
			}
			return errors.New("timed out verifying upgraded service executable")
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(100 * time.Millisecond):
		}
	}
}
